# 规格说明（B6 任务书 §二.⑤ registry 全公式零错门——fixture 对账半边；
#   KaTeX 零 throw 半边在 webapp vitest formulaKatexGate.test.ts）
#
# 【行为规格】
#   R1 重生成=子进程干净装载面（discover_units+elevation.losses+
#      network.manning——_REGISTRY 进程内全局单例，上游套件临时公式
#      污染防线，test_formula_printers.clean_registry_outputs 同款先例）；
#      stdout 经 sys.stdout.buffer 写出（零换行翻译——字节级比对前提）。
#   R2 对账面=逐字节（committed bytes == regenerated bytes——序列化
#      形=json.dumps(rows, ensure_ascii=False, indent=2)+"\\n"，UTF-8；
#      换行纪律=.gitattributes 钉 *.json eol=lf 跨平台检出恒 LF）。
#   R3 形状：恰 451 条（业务线扩充时同步——test_formula_printers 同源
#      计数）+formula_id 升序全序+latex 逐条非空（禁吞错空串）。
#
# 【测试要求】本件两用例（对账+形状）——漂移修复路径=跑
